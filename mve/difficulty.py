#!/usr/bin/env python3
"""Adaptive question difficulty (modeled on the study-companion plugin's `difficulty_policy.py`).

How the study-companion plugin does it
--------------------------------------
`DifficultyPolicy.select()` is a **pure function** that only reads server-side private data and outputs 2/3/4:

    combined = (normalized seed difficulty + mastery) / 2
    level    = <0.35 → 2,  <0.65 → 3,  otherwise → 4
    blockers present       → forced to 2
    reason=retry           → -1 (and no stacking a recent wrong streak on top; at most one step down per time)
    last two questions both correct → +1
    last two questions both wrong   → -1
    insufficient evidence (attempts<3 / confidence<0.6 / low_confidence flag) → capped at 3
    finally clamp to [2, 4]

Key point: the plugin's questions are **generated by (knowledge point, difficulty)** — difficulty is a
**parameter** of question generation, not a constant baked into each question. 82 seed knowledge points ×
3 difficulty tiers = the gradient.

Why MVE can't copy it directly
-------------------------------
MVE's 6 questions are **hard-coded**: each question = one knowledge point × a fixed difficulty (1/2/2/3/3/4).
There is no "harder version of the same knowledge point", so the plugin's `retry → difficulty -= 1`
has **nowhere to land** in MVE — when retrying a wrong question there is no simpler same-knowledge-point
question to switch to.

Questions also can't be freely generated by the LLM: grading relies on `answer_spec` (a server-side recipe),
and newly generated questions have no answer_spec, leaving the referee no way to independently compute the
expected answer — that's a hard boundary.

So the isomorphic relationship must switch dimensions: the plugin tunes **question difficulty**, while
what MVE can tune is the **scaffold tier** (scaffolding — from full support to full release):

    Plugin: same knowledge point, difficulty 2 → 3 → 4 (the question gets harder)
    MVE:    same question, scaffold full → partial → none (question unchanged, support gets thinner)

Scaffold adjustment only changes **how much the prompt gives**, not `answer_spec`, so the scoring points
stay the same, the referee grades as before, and mastery is computed as before — that's why it works.

Three scaffold tiers
--------------------
    full    — give the ★ declaration convention path; when the critic loops back, list the real candidate paths
    partial — give the focused structural documentation, but **no ★**; the critic only says "came back empty", no candidates
    none    — structural documentation not focused (full truncation); no ★, critic only says "came back empty"

Criteria (mirroring the plugin, isomorphic item by item)
--------------------------------------------------------
    insufficient evidence / low mastery → full (prop up first)
    two correct in a row → remove one scaffold tier (no longer needs support)
    two wrong in a row   → add one scaffold tier
    wrong_retry          → full (the plugin lowers difficulty; MVE's difficulty is fixed, so add scaffold instead)
"""

from __future__ import annotations

from typing import Any, Sequence

HINT_FULL = "full"
HINT_PARTIAL = "partial"
HINT_NONE = "none"
HINT_ORDER = [HINT_NONE, HINT_PARTIAL, HINT_FULL]   # higher index = more support

HINT_LABEL = {
    HINT_FULL: "full scaffold (★ declaration convention + candidate-path feedback)",
    HINT_PARTIAL: "partial support (structural documentation only, no convention path)",
    HINT_NONE: "release (no focusing, no convention, no candidates)",
}

# The plugin is 2..4; MVE's question set is 1..4, so it's normalized to 1..4 here
MIN_DIFFICULTY = 1
MAX_DIFFICULTY = 4

LOW_EVIDENCE_ATTEMPTS = 3
LOW_CONFIDENCE = 0.6


def _unit(value: Any, default: float = 0.0) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        return default
    if v != v or v in (float("inf"), float("-inf")):
        return default
    return min(1.0, max(0.0, v))


def seed_unit(difficulty: Any) -> float:
    """Question's fixed difficulty 1..4 → 0..1."""
    d = _unit(difficulty, default=0.4) * MAX_DIFFICULTY
    if d < 1:
        d = 1.0
    return (d - MIN_DIFFICULTY) / (MAX_DIFFICULTY - MIN_DIFFICULTY)


def _level(combined: float) -> int:
    if combined < 0.30:
        return 1
    if combined < 0.55:
        return 2
    if combined < 0.78:
        return 3
    return 4


def _verdicts(recent: Any) -> tuple[str, ...]:
    if not isinstance(recent, Sequence) or isinstance(recent, (str, bytes)):
        return ()
    out = []
    for item in recent:
        if isinstance(item, dict):
            item = item.get("verdict") or ""
        v = str(item or "").strip().lower()
        if v:
            out.append(v)
    return tuple(out)


def _streak(verdicts: tuple[str, ...], want: set[str]) -> bool:
    return len(verdicts) >= 2 and verdicts[-1] in want and verdicts[-2] in want


def select(
    seed_difficulty: Any,
    *,
    mastery: Any = 0.0,
    coverage: Any = None,
    attempts: Any = 0,
    confidence: Any = 0.0,
    flags: Sequence[Any] = (),
    recent_verdicts: Any = (),
    reason: str = "",
    blockers: Sequence[Any] = (),
    prev_hint: Any = "",
) -> dict[str, Any]:
    """Compute what difficulty this question should be at and how much scaffold to give. Returns {difficulty, hint, why}."""
    m = _unit(mastery, default=0.0)
    combined = (seed_unit(seed_difficulty) + m) / 2.0
    difficulty = _level(combined)
    why = [f"average of seed difficulty {seed_difficulty} and mastery {m:.2f} → difficulty {difficulty}"]

    if any(True for _ in (blockers or ())):
        difficulty = MIN_DIFFICULTY
        why.append(f"unresolved prerequisite blockers → pushed down to {MIN_DIFFICULTY}")

    hits = HINT_ORDER.index(HINT_PARTIAL)      # default: partial support
    norm = str(reason or "").strip().lower()
    is_retry = norm in {"retry", "wrong_retry"}

    if is_retry:
        difficulty -= 1
        why.append("wrong-question retry → difficulty -1")

    verdicts = _verdicts(recent_verdicts)
    if not is_retry:
        if _streak(verdicts, {"correct"}):
            difficulty += 1
            hits -= 1
            why.append("two correct in a row recently → difficulty +1, scaffold down one tier")
        elif _streak(verdicts, {"wrong", "dont_know"}):
            difficulty -= 1
            hits += 1
            why.append("two wrong in a row recently → difficulty -1, scaffold up one tier")

    try:
        att = max(0, int(attempts or 0))
    except (TypeError, ValueError):
        att = 0
    conf = _unit(confidence, default=0.0)
    low_flag = any(str(f or "").strip().lower() == "low_confidence" for f in (flags or ()))
    low_evidence = att < LOW_EVIDENCE_ATTEMPTS or conf < LOW_CONFIDENCE or low_flag
    # ---- Scaffold criteria (strongest to weakest priority) ----
    #
    # The primary criterion is **coverage** (can it actually do it), not mastery: low mastery may just
    # mean "there's little evidence yet" (V2's confidence gets dragged down by the number of evidence
    # items), which is not the same as "can't do it yet".
    # Using mastery as the primary criterion produces false positives like "everything answered
    # correctly yet the scaffold gets removed anyway".
    if is_retry or norm in {"all_stalled", "blocked_diagnostic"}:
        hits = HINT_ORDER.index(HINT_FULL)
        why.append("wrong question · stalled · no evidence → full scaffold")
    elif low_evidence:
        hits = HINT_ORDER.index(HINT_FULL)
        why.append(f"insufficient evidence (practiced {att} times · confidence {conf:.2f}) → difficulty capped at 3, full scaffold")
    else:
        cov = _unit(coverage, default=0.0)
        if cov >= 1.0:
            hits = HINT_ORDER.index(HINT_NONE)
            why.append(f"coverage {cov:.0%} already perfect → release (skill already in library, next round runs the program directly)")
        elif cov >= 0.6:
            hits = HINT_ORDER.index(HINT_PARTIAL)
            why.append(f"coverage {cov:.0%} → partial support")
        else:
            hits = HINT_ORDER.index(HINT_FULL)
            why.append(f"coverage {cov:.0%} low → full scaffold")

    # Mastery is only used to **remove** support, never to add it: once it can do it, stop propping it up
    if m >= 0.80:
        hits = min(hits, HINT_ORDER.index(HINT_NONE))
        why.append(f"mastery {m:.2f} already at standard → release")
    elif m >= 0.60:
        hits = min(hits, HINT_ORDER.index(HINT_PARTIAL))
        why.append(f"mastery {m:.2f} → partial support")

    difficulty = min(MAX_DIFFICULTY, max(MIN_DIFFICULTY, difficulty))
    hits = min(len(HINT_ORDER) - 1, max(0, hits))
    # ---- Tier smoothing: **at most one tier of removal/addition per round** (mirroring the plugin) ----
    #
    # The plugin's original text (`difficulty_policy.py:117-120`):
    #     "A retry already has its one-step decrease.  Do not stack a recent
    #      wrong streak onto it: a retry must never drop more than one level."
    # Two correct → difficulty +1 is likewise a single tier. **A gradient is walked, not jumped.**
    #
    # The observed consequence without this constraint: the criterion is "this round's coverage", and
    # the full tier with the knowledge graph hits 100% on the first try → jumps straight to none →
    # remove the knowledge graph and it crashes back to 0% → two wrongs jump back to full — the tier
    # oscillates between full↔none, and **the partial tier is never practiced**. That's the mechanism
    # behind the dashboard's "baseline exam 16% → post-practice retest 16% (flat) → final exam 0%":
    # the model only ever experiences the two worlds of "everything given" and "everything taken away",
    # so gradual competence never has a chance to form.
    ph = str(prev_hint or "").strip().lower()
    if ph in HINT_ORDER:
        pi = HINT_ORDER.index(ph)
        if hits > pi + 1:
            hits = pi + 1
            why.append(f"last round's scaffold was {ph}, at most one tier of removal per round → {HINT_ORDER[hits]}")
        elif hits < pi - 1:
            hits = pi - 1
            why.append(f"last round's scaffold was {ph}, at most one tier of addition per round → {HINT_ORDER[hits]}")
    return {"difficulty": difficulty, "hint": HINT_ORDER[hits], "why": "; ".join(why)}


def hint_allows(hint: str, what: str) -> bool:
    """What a scaffold tier is allowed to give. `what` ∈ {declared, candidates, focus}."""
    h = str(hint or HINT_PARTIAL)
    table = {
        "declared": {HINT_FULL},
        "candidates": {HINT_FULL},
        "focus": {HINT_FULL, HINT_PARTIAL},
    }
    return h in table.get(what, set())
